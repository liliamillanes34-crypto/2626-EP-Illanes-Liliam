# Tarea Semana 9 - Arreglo simple

# 1. Crear el arreglo con los cinco valores (10, 20, 30, 40, 50)
numeros = [10, 20, 30, 40, 50]

# 2. Mostrar el valor de la POSICION 1
print("El numero de la posicion 1 es:", numeros [1])

# 3. Recorrer todo el arreglo e imprimir cada elemento
print("Todos los elementos del arreglo:")
for numero in numeros:
    print(numero)
